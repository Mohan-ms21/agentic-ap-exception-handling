// Regenerates src/lib/eval/dataset.generated.ts from the eval CSVs.
// Run after replacing a CSV: npm run generate:eval
// A unit test fails if the generated module and the CSVs drift apart.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseCsvRecords } from "./csv.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const DATASET_CSV =
  "eval/ap_price_variance_combined_eval_dataset_v4.csv";
export const FIXTURES_CSV = "eval/ap_price_variance_eval_fixtures_v4.csv";
const OUTPUT = "src/lib/eval/dataset.generated.ts";

const read = (path) => parseCsvRecords(readFileSync(join(root, path), "utf8"));

const source = `// Generated by \`npm run generate:eval\` from ${DATASET_CSV}
// and ${FIXTURES_CSV}. Do not edit by hand.

export const evalDatasetRows: ReadonlyArray<Readonly<Record<string, string>>> =
  ${JSON.stringify(read(DATASET_CSV), null, 2)};

export const evalFixtureRows: ReadonlyArray<Readonly<Record<string, string>>> =
  ${JSON.stringify(read(FIXTURES_CSV), null, 2)};
`;

writeFileSync(join(root, OUTPUT), source);
console.log(`Wrote ${OUTPUT}`);
