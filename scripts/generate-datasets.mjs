// Regenerates the typed dataset modules from the CSVs:
//   eval/*.csv                       -> src/lib/eval/dataset.generated.ts
//   data/batch/*.csv                 -> src/lib/batch/batch-intake.generated.ts
//   eval/runs/<run>.csv (optional)   -> src/lib/eval/runs.generated.ts
// Run after replacing a CSV: npm run generate:data
// Unit tests fail if a generated module and its CSV drift apart.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseCsvRecords } from "./csv.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export const DATASET_CSV =
  "eval/ap_price_variance_combined_eval_dataset_v4.csv";
export const FIXTURES_CSV = "eval/ap_price_variance_eval_fixtures_v4.csv";
export const BATCH_CSV = "data/batch/ap_batch_intake_demo_v2.csv";

const read = (path) => parseCsvRecords(readFileSync(join(root, path), "utf8"));

/** Evaluation run slots; a missing export generates null. */
export const RUN_EXPORTS = {
  baseline: "eval/runs/baseline.csv",
  hardened: "eval/runs/hardened.csv",
};

const rowsType = "ReadonlyArray<Readonly<Record<string, string>>>";

const outputs = [
  {
    file: "src/lib/eval/dataset.generated.ts",
    sources: [DATASET_CSV, FIXTURES_CSV],
    exports: [
      ["evalDatasetRows", DATASET_CSV],
      ["evalFixtureRows", FIXTURES_CSV],
    ],
  },
  {
    file: "src/lib/batch/batch-intake.generated.ts",
    sources: [BATCH_CSV],
    exports: [["batchIntakeRows", BATCH_CSV]],
  },
];

{
  const entries = Object.entries(RUN_EXPORTS).map(([slot, path]) => {
    const rows = existsSync(join(root, path))
      ? JSON.stringify(read(path), null, 2)
      : "null";
    return `  ${slot}: ${rows},`;
  });
  const source =
    `// Generated by \`npm run generate:data\` from the optional exports in eval/runs/.\n` +
    `// Do not edit by hand. null means the run has not been imported.\n\n` +
    `export const evalRunExports: Readonly<Record<"baseline" | "hardened", ReadonlyArray<Readonly<Record<string, string>>> | null>> = {\n` +
    entries.join("\n") +
    `\n};\n`;
  writeFileSync(join(root, "src/lib/eval/runs.generated.ts"), source);
  console.log("Wrote src/lib/eval/runs.generated.ts");
}

for (const output of outputs) {
  const header =
    `// Generated by \`npm run generate:data\` from ${output.sources.join("\n// and ")}.\n` +
    `// Do not edit by hand.\n`;
  const body = output.exports
    .map(
      ([name, csv]) =>
        `\nexport const ${name}: ${rowsType} =\n  ${JSON.stringify(read(csv), null, 2)};\n`,
    )
    .join("");
  writeFileSync(join(root, output.file), header + body);
  console.log(`Wrote ${output.file}`);
}
